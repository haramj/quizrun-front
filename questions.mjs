const aliases = {
 '개발': /코딩|자바|react|javascript|컴퓨터|프로그래밍/i,
 '과학': /우주|물리|생물/, '역사': /한국사|조선/, '스포츠': /축구|농구|야구|운동/,
 '영화': /시네마|무비/, '음악': /노래|악기/, '상식': /종합|일반/,
 '지리': /나라|수도|세계지도/, '음식': /요리|먹거리/, '동물': /곤충|포유류/,
 '언어': /영어|국어|단어/, '수학': /계산|숫자/, '미술': /그림|색채/,
 '게임': /체스|오목|스도쿠/, '환경': /생태|재활용|에너지/
};
export function resolveTopic(keyword) {
 const value=String(keyword).trim();
 const topic=topics.find(t=>value===t)||topics.find(t=>value.includes(t))||topics.find(t=>aliases[t]?.test(value));
 if(!topic)throw Error('지원하는 카테고리를 선택해 주세요: '+topics.join(' · '));
 return topic;
}
function shuffle(values) {
 const result=[...values];
 for(let i=result.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[result[i],result[j]]=[result[j],result[i]];}
 return result;
}
export function makeQuestions(keyword,count) {
 const bank=banks[resolveTopic(keyword)];
 if(!Number.isInteger(count)||count<1||count>bank.length)throw Error('문제 수는 1~'+bank.length+'개여야 해요.');
 return shuffle(bank).slice(0,count).map(([text,options,answer])=>{
  const order=shuffle([0,1,2,3]);
  return {text,options:order.map(i=>options[i]),answer:order.indexOf(answer)};
 });
}
